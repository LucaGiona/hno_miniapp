export function t(key, vars) {
  const dict = S[getLang()] || S.de;
  let s = dict[key];
  if (s == null) s = S.de[key];
  if (s == null) return key;
  if (vars) Object.keys(vars).forEach((k) => { s = s.split('{' + k + '}').join(vars[k]); });
  return s;
}

export function catName(cat) {
  const m = CAT_NAMES[getLang()];
  return (m && m[cat]) || cat;
}

/* Statische Texte im HTML: data-i (Text), data-html (HTML aus dieser Datei), data-ph (Platzhalter),
   data-aria (aria-label), data-title (title) */
export function applyStatic(vars) {
  document.documentElement.lang = getLang();
  document.querySelectorAll('[data-i]').forEach((n) => { n.textContent = t(n.getAttribute('data-i'), vars); });
  document.querySelectorAll('[data-html]').forEach((n) => { n.innerHTML = t(n.getAttribute('data-html'), vars); });
  document.querySelectorAll('[data-ph]').forEach((n) => { n.placeholder = t(n.getAttribute('data-ph')); });
  document.querySelectorAll('[data-aria]').forEach((n) => { n.setAttribute('aria-label', t(n.getAttribute('data-aria'))); });
  document.querySelectorAll('[data-title]').forEach((n) => { n.title = t(n.getAttribute('data-title')); });
}
